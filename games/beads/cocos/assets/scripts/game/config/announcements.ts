/**
 * 公告内容表（玩家可见的「版本说明 / 维护通知」）— WXG-T-495。
 *
 * 定位与上位：
 * - 裁定正本 = `design/ux/ux-spec.md` **§8 U19**。用户 2026-10-29 裁「首版不做强运营，
 *   公告跟着版本走」⇒ ① 内容源 = **本地随包文案表**（本文件）；② 面板实装节点 = 独立批
 *   （消息中心弹窗内排版未定，本批不落 UI）；③ 提示位口径（是否共用信封红点）仍待裁。
 * - 面板方向已由 WXG-T-494 裁定：公告 = 信封（消息中心）弹窗内的一类内容，
 *   ⛔ 不占顶栏位、⛔ 不另开二级弹窗。
 *
 * 纪律（照 `copy-tokens.ts` 与 `arcs.ts` 的判例）：
 * - 本文件是**运营内容数据**，不是 UI 文案令牌 —— ⛔ 不进 `copy-tokens.ts`（那份只收设计表
 *   已登记的界面文案，且不得自加键）；也不住 `tuning`（不是数值、不涉 §3 冻结常量）。
 * - **数组顺序 = 展示顺序（新在上）**：发版时在数组**头部**加一条，⛔ 不排序、不插入中间。
 * - `id` 一经发布**不改不删不复用**（同 `arcs.ts` 的稳定 id 判例）；将来做「已读」也只认 id。
 * - `date` = 对外可见日（`YYYY-MM-DD`）；⛔ 不写未发生的发布日。
 * - `title` / `body` 是上屏纯文本：body **单段**（面板按现有宽度折行），⛔ 换行符、⛔ 富文本、
 *   ⛔ 「点击查看」类引导（面板无跳转能力）。
 * - 换远端（上线后另办域名/备案，见 U19）：条目形状即远端返回形状 ⇒ 换源只换读取方，
 *   面板与本表零改；平台无关 GET 已存在于 `packages/framework/src/platform/platform.ts`。
 *
 * 现状 = **空表**：尚无已发生的对外发布事件（首条在提审前由运营填写形状如下）：
 * `{ id: 'v1.0.1-fix', date: '2026-11-01', title: 'v1.0.1 更新', body: '修复若干已知问题。' }`
 */
export interface AnnouncementEntry {
    /** 稳定标识（全表唯一；已发布的条目不改不删不复用）。 */
    readonly id: string;
    /** 对外可见日，`YYYY-MM-DD`。 */
    readonly date: string;
    /** 条目标题（一行，建议 ≤ 16 字）。 */
    readonly title: string;
    /** 正文：单段纯文本，面板折行。 */
    readonly body: string;
}

/** 公告表。顺序即展示顺序（新在上）；⛔ 不要在中间插入。 */
export const ANNOUNCEMENTS: readonly AnnouncementEntry[] = [];
